"""Builds the big haunted mansion's facade and the garden shed from the mansion sprite in the
environment atlas (assets/env/atlas.png, 'mansion_front' 224x138): the two-storey body becomes
three storeys, the towers four, lower wings are added outside the towers, and the gable gets a
balcony on every floor. Writes assets/env/mansion_big.png, assets/env/shed.png and the glowing
window positions to js/ai/87-mansion-art.js.

  python3 tools/mansion_art.py
"""
import json
from PIL import Image

ATLAS = 'assets/env/atlas.png'
src = Image.open(ATLAS).convert('RGBA').crop((0, 0, 224, 138))


def cut(x0, y0, x1, y1, flip=False):
    im = src.crop((x0, y0, x1, y1))
    return im.transpose(Image.FLIP_LEFT_RIGHT) if flip else im


def stack(parts):
    w = max(p.width for p in parts)
    out = Image.new('RGBA', (w, sum(p.height for p in parts)))
    y = 0
    for p in parts:
        out.alpha_composite(p, (0, y)); y += p.height
    return out


def body(x0, x1, flip=False):
    # roof, then three storeys (the upper storey band repeated, an eave between each)
    # (the middle storey is the upper one mirrored, so the floors don't repeat exactly)
    return stack([cut(x0, 34, x1, 80, flip), cut(x0, 80, x1, 104, flip), cut(x0, 104, x1, 112, flip),
                  cut(x0, 80, x1, 104, not flip), cut(x0, 104, x1, 112, flip), cut(x0, 112, x1, 138, flip)])


def tower(x0, x1):
    return stack([cut(x0, 0, x1, 46), cut(x0, 46, x1, 71), cut(x0, 71, x1, 103), cut(x0, 71, x1, 103), cut(x0, 103, x1, 138)])


def wing(flip):
    # a lower, two-storey wing outside each tower
    return cut(33, 34, 94, 138, flip)


H = 170
# (sections are cut one pixel inside the towers' dark edges, so mirrored pairs join without a seam)
cols = [wing(True), tower(0, 32), body(33, 94, True), body(33, 94), body(94, 130), body(130, 191), body(130, 191, True), tower(192, 224), wing(False)]
W = sum(c.width for c in cols)
big = Image.new('RGBA', (W, H))
x = 0
for c in cols:
    big.alpha_composite(c, (x, H - c.height)); x += c.width
big.save('assets/env/mansion_big.png')

# glowing windows: purple and warm panes, as light positions relative to the door (bottom centre)
px = big.load()
seen, wins = set(), []
for y in range(H):
    for x in range(W):
        r, g, b, a = px[x, y]
        warm = r > 200 and g > 170 and b < 170 and a > 0
        purple = r > 150 and b > 200 and g < 120 and a > 0
        if not (warm or purple) or (x, y) in seen:
            continue
        # flood the pane
        q, pts = [(x, y)], []
        while q:
            cx, cy = q.pop()
            if (cx, cy) in seen or not (0 <= cx < W and 0 <= cy < H):
                continue
            rr, gg, bb, aa = px[cx, cy]
            if not ((rr > 200 and gg > 170 and bb < 170) or (rr > 150 and bb > 200 and gg < 120)) or aa == 0:
                continue
            seen.add((cx, cy)); pts.append((cx, cy))
            q += [(cx + 1, cy), (cx - 1, cy), (cx, cy + 1), (cx, cy - 1)]
        if len(pts) < 6:
            continue
        mx = sum(p[0] for p in pts) / len(pts); my = sum(p[1] for p in pts) / len(pts)
        wins.append([round((mx - W / 2) * 2), round((H - my) * 2), 'w' if warm else 'p'])

# the shed: a short stretch of wall and roof from the wing, its doors are drawn by the game
shed = stack([cut(33, 46, 94, 80), cut(33, 112, 94, 138)])
shed.save('assets/env/shed.png')

meta = {'mansion': {'w': W, 'h': H, 'wins': wins}, 'shed': {'w': shed.width, 'h': shed.height}}
with open('js/ai/87-mansion-art.js', 'w', encoding='utf-8') as f:
    f.write('/* PokéSurvivor+ — the big mansion facade and the shed (generated by tools/mansion_art.py) */\n')
    f.write('window.PSXAI_MANSION_ART = ' + json.dumps(meta, separators=(',', ':')) + ';\n')
print(W, H, len(wins), shed.size)
