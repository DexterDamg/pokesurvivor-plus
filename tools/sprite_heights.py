#!/usr/bin/env python3
"""How tall each Pokémon's sprite really is (its opaque pixels, not the padded frame), for
accurate sizes (js/ai/14-scale.js). Reads assets/pokemon/<dex>/Idle.png with the frame sizes in
tools/sprite_idle_meta.json (dumped from the game's SPRITE_META) and writes js/ai/12-spriteh.js.
The facing-down row (the first) is measured; the tallest frame of the idle loop counts."""
import json, os
import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..')
meta = json.load(open(os.path.join(ROOT, 'tools', 'sprite_idle_meta.json')))
out = {}
for k, a in sorted(meta.items(), key=lambda kv: (int(kv[0].split('_')[0]), kv[0])):
    p = os.path.join(ROOT, 'assets', 'pokemon', k, 'Idle.png')
    if not os.path.exists(p):
        continue
    al = np.array(Image.open(p).convert('RGBA'))[:, :, 3]
    fw, fh = a['w'], a['h']
    best = 0
    for c in range(al.shape[1] // fw):
        f = al[0:fh, c * fw:(c + 1) * fw]
        ys = np.where(f.max(1) > 40)[0]
        if len(ys):
            best = max(best, int(ys[-1] - ys[0] + 1))
    if best:
        out[k] = best
js = ('/* PokéSurvivor+ — Living World AI · how tall each Pokémon\'s sprite really is (opaque pixels of its idle\n'
      ' * frames, facing down), by dex number (forms as "493_bug"…). Generated by tools/sprite_heights.py: do not edit. */\n'
      'window.PSXAI_SPRITE_H = ' + json.dumps(out, separators=(',', ':')) + ';\n')
open(os.path.join(ROOT, 'js', 'ai', '12-spriteh.js'), 'w').write(js)
print(len(out), 'sprites measured')
